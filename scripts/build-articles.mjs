// Turns content/articles/*.md into src/articles.generated.js.
// Supports: frontmatter (title, slug, date, description, status, sources), ## headings,
// paragraphs, "- " lists, **bold**, *italic*, [links](url).

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { markdown } from "../src/markdown.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "content", "articles");

function frontmatter(src, file) {
  const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const meta = { sources: [] };
  let inSources = false, cur = null;
  for (const line of m[1].split(/\r?\n/)) {
    if (/^sources:\s*$/.test(line)) { inSources = true; continue; }
    if (inSources) {
      const item = line.match(/^\s*-\s*(\w+):\s*(.*)$/);
      const field = line.match(/^\s+(\w+):\s*(.*)$/);
      if (item) { cur = { [item[1]]: item[2].trim() }; meta.sources.push(cur); continue; }
      if (field && cur) { cur[field[1]] = field[2].trim(); continue; }
      inSources = false;
    }
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2].trim().replace(/^["']|["']$/g, "");
  }
  for (const k of ["title", "slug", "date", "description", "status"]) if (!meta[k]) throw new Error(`${file}: missing ${k}`);
  if (!["draft", "published"].includes(meta.status)) throw new Error(`${file}: status must be draft or published`);
  return { meta, body: m[2] };
}

const articles = readdirSync(dir).filter((f) => f.endsWith(".md")).map((f) => {
  const { meta, body } = frontmatter(readFileSync(join(dir, f), "utf8"), f);
  return { slug: meta.slug, title: meta.title, date: meta.date, description: meta.description, status: meta.status, sources: meta.sources, html: markdown(body) };
}).sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));

writeFileSync(join(root, "src", "articles.generated.js"), `// Generated by scripts/build-articles.mjs. Do not edit.\nexport const ARTICLES = ${JSON.stringify(articles, null, 1)};\n`);
console.log(`articles: ${articles.filter((a) => a.status === "published").length} published, ${articles.filter((a) => a.status === "draft").length} draft`);
